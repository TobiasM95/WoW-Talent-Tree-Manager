-- Drop every cached solve written before the result-header fix.
--
-- The CLI reported each result bit as a talent's rank among the talents of the *solved DAG*,
-- which excludes granted (pre-filled) roots, while the worker read it as a rank among every
-- talent of the tree. On any tree with a granted root -- every class tree and every hero
-- tree -- each talent after that root was therefore stored as its neighbour: a full hero
-- build came back as "the granted talent plus the first twelve", without its capstone.
--
-- Counts were never affected; only which talents a stored result named. Because jobs double
-- as a cache keyed by request, those wrong rows would otherwise keep being served for every
-- identical request. They are a cache, so dropping them loses nothing that cannot be
-- recomputed, and solve_results and solve_stats follow by cascade.
--
-- The API also versions its cache key from now on (SOLVE_CONTRACT in app.py), so the next
-- change to what a result means invalidates old rows without needing a migration.
DELETE FROM solve_jobs;
